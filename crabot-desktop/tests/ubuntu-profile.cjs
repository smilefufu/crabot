// Real Electron profile-selection mechanism; no application services are started.
const { app, session, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = fs.realpathSync(process.env.CRABOT_UBUNTU_PROFILE_TEST_ROOT)
const first = path.join(root, 'first/desktop-profile'), second = path.join(root, 'second/desktop-profile')
for (const directory of [first, second]) fs.mkdirSync(directory, { recursive: true, mode: 0o700 })
app.setPath('userData', first); app.setPath('sessionData', first)
app.whenReady().then(async () => {
  const original = session.fromPartition('persist:crabot-desktop')
  await original.cookies.set({ url: 'https://crabot.invalid', name: 'choice', value: 'first', expirationDate: Date.now() / 1000 + 3600 })
  app.setPath('userData', second); app.setPath('sessionData', second)
  assert.equal(session.fromPartition('persist:crabot-desktop'), original)
  assert.ok(original.storagePath.startsWith(first + path.sep), 'partition cache reproduces the stale profile')
  const storage = path.join(second, 'Partitions/crabot-desktop'), selected = session.fromPath(storage)
  assert.equal(selected.storagePath, storage)
  assert.equal((await selected.cookies.get({ name: 'choice' })).length, 0)
  await selected.cookies.set({ url: 'https://crabot.invalid', name: 'choice', value: 'second', expirationDate: Date.now() / 1000 + 3600 })
  await selected.cookies.flushStore()
  assert.equal((await original.cookies.get({ name: 'choice' }))[0].value, 'first')
  assert.equal((await selected.cookies.get({ name: 'choice' }))[0].value, 'second')
  const window = new BrowserWindow({ show: false, webPreferences: { session: selected, sandbox: true, contextIsolation: true, nodeIntegration: false } })
  await window.loadURL('about:blank')
  assert.equal(window.webContents.session, selected)
  assert.equal(window.webContents.getLastWebPreferences().sandbox, true)
  console.log('CRABOT_UBUNTU_PROFILE ' + JSON.stringify({ actual_electron: true, old_partition_cache_reproduced: true,
    selected_profile_path: true, cookies_isolated: true, sandbox_preserved: true, business_mm_started: false }))
  app.exit(0)
}).catch(error => { console.error(error.stack); app.exit(1) })
